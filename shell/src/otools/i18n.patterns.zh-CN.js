/**
 * 模式表：带插值的文案按形状认。
 * ------------------------------------------------------------------
 * 上游有大量文案是模板串拼出来的（`Alpha ${n}`、`${l.name} Vector Mask`），
 * 永远不可能成为词典的键，只能按形状认。
 *
 * 每条都是**锚定正则**（`^…$`，不带 `g`）。替换函数返回**空串**表示
 * 「这条不适用」，让文案保持英文并出现在缺口报告里——宁可半句英文，
 * 也别拼出「重置 Reset all」这种半成品。
 *
 * 第二参数 `t` 是翻译函数：捕获组若是界面文案（动作名、调整类型、模式名）
 * 就用 `t(组)` 递归再翻一次；若是用户数据（图层名、文件名、路径）就原样
 * 保留——**图层名和文件名绝不能被翻译**。
 *
 * ⚠️ **顺序即优先级**，从具体到宽泛。
 * ⚠️ `i18n-report.mjs` 不统计模式表，它只按词典算覆盖率——
 * 本文件的效果要在运行时看，别拿报告的百分比验收。
 */
export const patterns = [
  // ── 纯数值 + 单位 ──────────────────────────────────────────────
  [/^([\d.]+) pt$/, (m) => `${m[1]} 磅`],
  [/^([\d.]+) px$/, (m) => `${m[1]} 像素`],
  [/^([\d.]+) in$/, (m) => `${m[1]} 英寸`],

  // ── 文件名解析的报错（引号内是用户输入，必须保留）───────────────
  [/^“(.+)” is not a supported extension \(use png, jpg, webp, gif or svg\)\.$/,
    (m) => `“${m[1]}”不是受支持的扩展名（请使用 png、jpg、webp、gif 或 svg）。`],
  [/^“(.+)” is not valid \(use \.png, \.png8, \.png24 or \.png32\)\.$/,
    (m) => `“${m[1]}”无效（请使用 .png、.png8、.png24 或 .png32）。`],
  [/^“(.+)” has a % without a quality\.$/, (m) => `“${m[1]}”含有 % 但没有指定质量。`],
  [/^The quality in “(.+)” must be 1 to 100\.$/, (m) => `“${m[1]}”中的质量必须为 1 到 100。`],
  [/^“\.(.+)” takes no quality or option \(in “(.+)”\)\.$/,
    (m) => `“.${m[1]}”不接受质量或选项（位于“${m[2]}”中）。`],
  [/^“(.+)” has no file name before the extension\.$/, (m) => `“${m[1]}”在扩展名之前没有文件名。`],
  [/^“(.+)”: SVG needs a shape or text layer, or a group of only those\.$/,
    (m) => `“${m[1]}”：SVG 需要形状图层或文字图层，或仅由它们组成的组。`],
  [/^“(.+)” could not be encoded: (.+)$/, (m) => `“${m[1]}”编码失败：${m[2]}`],

  // ── 参数超范围（含占位符 `{...}` 的会在 t() 里二次替换）─────────
  [/^(.+) (.+) is below the minimum; using (.+)\.$/, (m) => `${m[1]} 的 ${m[2]} 低于最小值；将使用 ${m[3]}。`],
  [/^(.+) (.+) is above the maximum; using (.+)\.$/, (m) => `${m[1]} 的 ${m[2]} 高于最大值；将使用 ${m[3]}。`],

  // ── 图层名后缀（图层名保留，只翻后缀）─────────────────────────
  [/^(.+) Vector Mask$/, (m) => `${m[1]} 矢量蒙版`],
  [/^(.+) Shape Path$/, (m) => `${m[1]} 形状路径`],
  [/^(.+) Type Path$/, (m) => `${m[1]} 文字路径`],
  [/^(.+) \(Refined\)$/, (m) => `${m[1]}（已细化）`],
  [/^(.+) copy$/, (m) => `${m[1]} 副本`],

  // ── 编号命名的对象与数据组 ─────────────────────────────────────
  [/^Object (\d+)$/, (m) => `对象 ${m[1]}`],
  [/^(.+) – Object (\d+)$/, (m) => `${m[1]} – 对象 ${m[2]}`],
  [/^Data Set (\d+)$/, (m) => `数据组 ${m[1]}`],
  [/^Frame (\d+)$/, (m) => `帧 ${m[1]}`],
  [/^Page (\d+)$/, (m) => `第 ${m[1]} 页`],
  [/^Path (\d+)$/, (m) => `路径 ${m[1]}`],
  [/^Alpha (\d+)$/, (m) => `Alpha ${m[1]}`],
  [/^Row (\d+), Column (\d+)$/, (m) => `第 ${m[1]} 行，第 ${m[2]} 列`],

  // ── 单位与读数 ─────────────────────────────────────────────────
  [/^(.+) Bits\/Channel$/, (m) => `${m[1]} 位/通道`],
  [/^(.+) swatches$/, (m) => `${m[1]} 个色板`],
  [/^Output resolution \(pixels\/inch; input (.+)\)$/, (m) => `输出分辨率（像素/英寸；输入 ${m[1]}）`],
  [/^This file has (\d+) (.+)s$/, (m, t) => `此文件有 ${m[1]} 个${t(m[2]) || m[2]}`],
  [/^Statistics \((.+)\)$/, (m, t) => `统计（${t(m[1]) || m[1]}）`],
  [/^Assisted \((.+)\)$/, (m, t) => `已辅助（${t(m[1]) || m[1]}）`],
  [/^Offline · (.+) pending$/, (m) => `离线 · ${m[1]} 项待处理`],
  [/^(.+) \((.+)\)$/, (m, t) => `${t(m[1]) || m[1]}（${m[2]}）`],

  // ── 导出格式 ───────────────────────────────────────────────────
  [/^(CMYK|RGB|Grayscale) TIFF \((.+)\)$/, (m, t) => `${t(m[1]) || m[1]} TIFF（${m[2]}）`],
  [/^Indexed PNG \((.+)\)$/, (m) => `索引 PNG（${m[1]}）`],
  [/^Export a (.+) with your last Export As settings$/, (m, t) => `使用上次「导出为」的设置导出${t(m[1]) || m[1]}`],

  // ── 动作与调整 ─────────────────────────────────────────────────
  [/^Action: (.+)$/, (m) => `动作：${m[1]}`],
  [/^Animate (.+)$/, (m, t) => `为 ${t(m[1]) || m[1]} 制作动画`],
  [/^Add a non-destructive (.+) adjustment layer$/, (m, t) => `添加非破坏性的「${t(m[1]) || m[1]}」调整图层`],
  [/^Add or edit the (.+) effect$/, (m, t) => `添加或编辑「${t(m[1]) || m[1]}」效果`],
  [/^Add the (.+) to the library shown in the Libraries panel$/, (m, t) => `将「${t(m[1]) || m[1]}」添加到「库」面板中显示的库`],
  [/^Add (.+)$/, (m, t) => `添加 ${t(m[1]) || m[1]}`],
  [/^(Redefine|Delete) (.+)$/, (m, t) => `${m[1] === 'Redefine' ? '重新定义' : '删除'} ${t(m[2]) || m[2]}`],
  [/^(Rename|New) (.+)…$/, (m, t) => `${m[1] === 'Rename' ? '重命名' : '新建'} ${t(m[2]) || m[2]}…`],
  [/^Copy (.+)$/, (m, t) => `复制 ${t(m[1]) || m[1]}`],
  [/^(.+) caption$/, (m, t) => `${t(m[1]) || m[1]}题注`],
  [/^(.+) label$/, (m) => `${m[1]} 标签`],
  [/^(.+) panel$/, (m, t) => `${t(m[1]) || m[1]}面板`],
  [/^Placed (.+)$/, (m) => `已置入 ${m[1]}`],

  // ── 色彩和谐 / 模式 ────────────────────────────────────────────
  [/^(.+) Harmony from Foreground$/, (m, t) => `${t(m[1]) || m[1]}（取自前景色）`],
  [/^From (.+)$/, (m, t) => `来自${t(m[1]) || m[1]}`],
  [/^from-(.+)$/, () => ''],  // CSS 类名，不翻

  // ── 助手 / 选择工具 ────────────────────────────────────────────
  [/^Use (.+) for the Assistant$/, (m) => `助手使用 ${m[1]}`],
  [/^Matched “(.+)” by its name\.$/, (m) => `按名称匹配到“${m[1]}”。`],
  [/^Set (.+) point$/, (m, t) => `设置${t(m[1]) || m[1]}点`],
  [/^Sample in image to set (.+) point$/, (m, t) => `在图像中取样以设置${t(m[1]) || m[1]}点`],
  [/^(.+)\n\nA small preview of the visible image is attached\.$/, (m) => `${m[1]}\n\n随附可见图像的小预览。`],

  // ── 状态栏 ─────────────────────────────────────────────────────
  [/^Swatches (.+)$/, (m, t) => `色板 ${t(m[1]) || m[1]}`],
];
